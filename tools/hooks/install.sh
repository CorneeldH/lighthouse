#!/usr/bin/env bash
# Put the secret scan at the top of .git/hooks/pre-push (#194).
#
# Idempotent: a second run changes nothing. The scan goes ABOVE everything else in
# the hook, entire's line included: entire pushes its checkpoint refs itself with
# `git push --no-verify`, so a hook that runs after that line, or in the chain it
# calls (pre-push.pre-entire), sees them only after they left.
#
# Run it again after `entire enable --force` or `entire configure --force`: those
# rewrite pre-push and drop this block.
set -euo pipefail

HOOK_DIR="$(git rev-parse --path-format=absolute --git-common-dir)/hooks"
mkdir -p "$HOOK_DIR"
target="$HOOK_DIR/pre-push"

BEGIN="# >>> lighthouse secret scan (tools/hooks/install.sh) >>>"
END="# <<< lighthouse secret scan <<<"

# The block is POSIX sh: entire's own pre-push is #!/bin/sh.
block() {
  cat <<EOF
$BEGIN
# Generated by tools/hooks/install.sh — edit that script, not this block.
# .git/hooks is shared by every worktree but not tracked: the scan comes from the
# pushing checkout, or from the main checkout when this branch predates it. Neither
# there: refuse, never push unscanned.
_lh_top="\$(git rev-parse --show-toplevel)" || exit 1
_lh_main="\$(dirname "\$(git rev-parse --path-format=absolute --git-common-dir)")" || exit 1
_lh_scan=""
for _lh_dir in "\$_lh_top" "\$_lh_main"; do
  if [ -f "\$_lh_dir/tools/hooks/pre-push-secret-scan.sh" ]; then
    _lh_scan="\$_lh_dir/tools/hooks/pre-push-secret-scan.sh"
    break
  fi
done
if [ -z "\$_lh_scan" ]; then
  echo "pre-push: tools/hooks/pre-push-secret-scan.sh is in neither \$_lh_top nor \$_lh_main — refusing to push unscanned." >&2
  exit 1
fi
# The ref lines on stdin are for the rest of this hook too: keep a copy.
_lh_refs="\$(mktemp)" || exit 1
cat > "\$_lh_refs"
if ! bash "\$_lh_scan" "\$@" < "\$_lh_refs"; then
  rm -f "\$_lh_refs"
  exit 1
fi
exec < "\$_lh_refs"
rm -f "\$_lh_refs"
$END
EOF
}

if [ -f "$target" ]; then
  current="$(cat "$target")"
else
  current="#!/bin/sh"
fi

# Drop an earlier block, keep everything else.
rest="$(printf '%s\n' "$current" | awk -v b="$BEGIN" -v e="$END" '
  $0 == b { skip = 1; next }
  $0 == e { skip = 0; next }
  !skip { print }
')"

first="$(printf '%s\n' "$rest" | head -n 1)"
case "$first" in
  "#!"*) shebang="$first"; body="$(printf '%s\n' "$rest" | tail -n +2)" ;;
  *) shebang="#!/bin/sh"; body="$rest" ;;
esac

new="$(printf '%s\n%s\n%s\n' "$shebang" "$(block)" "$body")"
if [ "$new" = "$current" ]; then
  echo "install: secret scan already at the top of $target"
  exit 0
fi
printf '%s\n' "$new" > "$target"
chmod 0755 "$target"
echo "install: secret scan installed at the top of $target"
