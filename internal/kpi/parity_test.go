package kpi

import (
	"bytes"
	"encoding/json"
	"io"
	"os"
	"path/filepath"
	"testing"
)

type parityCase struct {
	Args   []string `json:"args"`
	RC     int      `json:"rc"`
	Stdout string   `json:"stdout"`
	Stderr string   `json:"stderr"`
}

// optionsFromArgs mirrors the command line: the first non-flag is the metric.
func optionsFromArgs(t *testing.T, args []string) Options {
	t.Helper()
	var opts Options
	for i := 0; i < len(args); i++ {
		switch args[i] {
		case "--dir":
			i++
			opts.Dir = args[i]
		case "--since":
			i++
			s := args[i]
			opts.Since = &s
		default:
			if opts.Metric != "" {
				t.Fatalf("unexpected argument %q in %v", args[i], args)
			}
			opts.Metric = args[i]
		}
	}
	return opts
}

// runParity runs every case of the shared fixtures under kind against run; the
// expectations were generated by the Python script, so a difference is a bug in the port.
func runParity(t *testing.T, kind string, run func(Options, io.Writer, io.Writer) int) {
	t.Helper()
	fixtures, err := filepath.Abs("../../tests/pack/fixtures/kpi")
	if err != nil {
		t.Fatal(err)
	}
	t.Setenv("LIGHTHOUSE_HEADINGS", filepath.Join(fixtures, "headings.toml"))
	t.Setenv("LIGHTHOUSE_TOML", filepath.Join(fixtures, "lighthouse.toml"))
	t.Setenv("LIGHTHOUSE_REPO_ROOT", fixtures)
	caseDirs, err := filepath.Glob(filepath.Join(fixtures, kind, "*", "expect.json"))
	if err != nil {
		t.Fatal(err)
	}
	if len(caseDirs) == 0 {
		t.Fatal("no " + kind + " fixture cases found")
	}
	ran := 0
	for _, expectPath := range caseDirs {
		dir := filepath.Dir(expectPath)
		data, err := os.ReadFile(expectPath)
		if err != nil {
			t.Fatal(err)
		}
		var cases []parityCase
		if err := json.Unmarshal(data, &cases); err != nil {
			t.Fatalf("%s: %v", expectPath, err)
		}
		for i, c := range cases {
			t.Run(filepath.Base(dir), func(t *testing.T) {
				t.Chdir(dir)
				var out, errOut bytes.Buffer
				rc := run(optionsFromArgs(t, c.Args), &out, &errOut)
				if rc != c.RC || out.String() != c.Stdout || errOut.String() != c.Stderr {
					t.Errorf("case %d %v:\nrc %d, want %d\nstdout %q\nwant   %q\nstderr %q\nwant   %q",
						i, c.Args, rc, c.RC, out.String(), c.Stdout, errOut.String(), c.Stderr)
				}
			})
			ran++
		}
	}
	if ran == 0 {
		t.Fatal("the fixtures hold no cases")
	}
}

func TestStartIssueParity(t *testing.T) { runParity(t, "start-issue", RunStartIssue) }

func TestFixPRParity(t *testing.T) { runParity(t, "fix-pr", RunFixPR) }
