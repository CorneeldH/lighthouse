var updatePlaces = flag.Bool("update", false, "rewrite testdata/places.golden from TestPlacesGolden")

const (
	placesGolden = "testdata/places.golden"
	placesHeader = "# Generated by TestPlacesGolden (internal/initcmd/places_test.go); rerun with -update.\n"
	workflowKey  = ".github/workflows/lighthouse-*.yml"
)

// placeOf maps a path init wrote to the place a user sees: a directory that lighthouse
// owns in whole, a glob for files with lighthouse's prefix, or the path itself.
func placeOf(rel string) string {
	for _, dir := range []string{packs.HookDir, ".lighthouse/lib/lighthouse_lib/", ".lighthouse/scripts/"} {
		if strings.HasPrefix(rel, dir) {
			return dir
		}
	}
	for _, prefix := range []string{".claude/skills/lighthouse-", ".agents/skills/lighthouse-"} {
		if strings.HasPrefix(rel, prefix) {
			return prefix + "*/"
		}
	}
	if strings.HasPrefix(rel, ".claude/agents/lighthouse-") {
		return ".claude/agents/lighthouse-*.md"
	}
	if strings.HasPrefix(rel, packs.WorkflowPrefix) {
		return workflowKey
	}
	return rel
}

func TestPlaceOf(t *testing.T) {
	for rel, want := range map[string]string{
		".claude/skills/lighthouse-go-standard/SKILL.md":      ".claude/skills/lighthouse-*/",
		".agents/skills/lighthouse-close-issue/refs/a.md":     ".agents/skills/lighthouse-*/",
		".claude/hooks/lighthouse/usage-gate/resume.py":       ".claude/hooks/lighthouse/",
		".lighthouse/lib/lighthouse_lib/config.py":            ".lighthouse/lib/lighthouse_lib/",
		".lighthouse/scripts/quality/ratchet.py":              ".lighthouse/scripts/",
		".claude/agents/lighthouse-issue-impact-scout.md":     ".claude/agents/lighthouse-*.md",
		".github/workflows/lighthouse-unblock-dependents.yml": ".github/workflows/lighthouse-*.yml",
		".github/pull_request_template.md":                    ".github/pull_request_template.md",
		"AGENTS.md":                                           "AGENTS.md",
	} {
		if got := placeOf(rel); got != want {
			t.Errorf("placeOf(%q) = %q, want %q", rel, got, want)
		}
	}
}

// TestPlacesGolden runs a real init with every package and pins each place it writes,
// with the kinds and packages that put something there.
func TestPlacesGolden(t *testing.T) {
	loaded, err := loadAll(pack.Files, "dev")
	if err != nil {
		t.Fatal(err)
	}
	var names []string
	for n := range loaded {
		names = append(names, n)
	}
	sort.Strings(names)

	root := newRepo(t)
	r := run(t, root, "", all(yes, func(o *Options) {
		o.Packs = nil
		o.AddPacks = names
		o.Lookup = func(string) (string, bool, error) { return "x", true, nil }
	}))
	if r.code != 0 {
		t.Fatalf("init exited %d: %s", r.code, r.err)
	}

	kinds := map[string]map[string]bool{}
	pkgs := map[string]map[string]bool{}
	touch := func(place string) {
		if kinds[place] == nil {
			kinds[place], pkgs[place] = map[string]bool{}, map[string]bool{}
		}
	}

	written := map[string]bool{}
	err = filepath.WalkDir(root, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			if d.Name() == ".git" {
				return filepath.SkipDir
			}
			return nil
		}
		rel, err := filepath.Rel(root, p)
		if err != nil {
			return err
		}
		written[filepath.ToSlash(rel)] = true
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}

	m, err := manifest.Read(root)
	if err != nil {
		t.Fatal(err)
	}
	inManifest := map[string]bool{}
	for _, e := range m.Units {
		place := placeOf(e.Path)
		touch(place)
		kinds[place][string(e.Kind)] = true
		pkgs[place][e.Package] = true
		inManifest[e.Path] = true
	}

	for rel := range written {
		if inManifest[rel] {
			continue
		}
		place := placeOf(rel)
		touch(place)
		kinds[place]["init"] = true
		if rel == configPath {
			pkgs[place]["core"] = true
			for _, n := range names {
				if len(loaded[n].Config) > 0 {
					pkgs[place][n] = true
				}
			}
		}
	}

	var lines []string
	for place := range kinds {
		lines = append(lines, place+"\t"+joinSet(kinds[place])+"\t"+joinSet(pkgs[place]))
	}
	sort.Strings(lines)
	got := []byte(placesHeader + strings.Join(lines, "\n") + "\n")

	if kinds[workflowKey] == nil {
		t.Fatal("no workflow installed: the Lookup stub must answer every key")
	}

	if *updatePlaces {
		if err := os.MkdirAll("testdata", 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(placesGolden, got, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(placesGolden)
	if err != nil {
		t.Fatal(err)
	}
	if string(want) != string(got) {
		t.Errorf("%s\nplaces.golden is stale: run go test ./internal/initcmd -run TestPlacesGolden -update, then bring the repo map in step (tests/test_site_repo.py)",
			unified(want, got, "places.golden", "init"))
	}
}

func joinSet(set map[string]bool) string {
	var out []string
	for k := range set {
		out = append(out, k)
	}
	sort.Strings(out)
	return strings.Join(out, ",")
}
